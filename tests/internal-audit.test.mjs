import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const code=readFileSync(new URL('../app/internal-audit.js',import.meta.url),'utf8');
const {inspectDocument,buildInternalAudit,applyAuditKnowledge,enrichPageResults,buildRewriteDraft,buildSpecificRecommendations}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const url='https://example.com/';
const html='<h1>会社</h1><h2>サービス</h2><ul><li>説明</li></ul><a href="/service">詳細</a><script type="application/ld+json">{"@graph":[{"@type":"Organization","name":"Example","url":"https://example.com"}]}</script>';
const doc=inspectDocument({html,text:'サービスとは。調査2026年、所在地と電話。',url});
assert.deepEqual(doc.jsonld.types,['Organization']);
assert.equal(doc.links[0],url+'service');
const audit=buildInternalAudit([{internalEvidence:doc}]);
assert.equal(audit.items.length,20);
assert.deepEqual(['コンテンツ','技術','サイト構造','信頼性','運用'].map(g=>audit.items.filter(x=>x.group===g).length),[6,4,3,3,4]);
assert.equal(audit.items.find(x=>x.id==='jsonld').state,'observed');
assert.equal(audit.items.find(x=>x.id==='visibility').state,'unknown');
const broken=inspectDocument({html:html.replace('{"@graph"','{oops "@graph"'),url});
assert.equal(broken.jsonld.invalid,1);
assert.equal(buildInternalAudit([{internalEvidence:broken}]).items.find(x=>x.id==='jsonld').state,'not_observed');
const fallback=buildInternalAudit([{internalEvidence:inspectDocument({text:'Organization FAQ 会社情報',url,source:'firecrawl'})}]);
for(const id of ['jsonld','html','links','entity'])assert.equal(fallback.items.find(x=>x.id===id).state,'unknown');
assert.ok(buildInternalAudit([]).items.every(x=>x.state==='unknown'));
assert.equal(audit.planning.measured,false);
const rich=inspectDocument({url:url+'service/',html:'<link href="/service/" rel="canonical"><main><section><h1>概要</h1><h2>条件</h2><p>サンプルとは、企業の情報発信を支援するサービスです。</p><a href="https://research.example.org/report">調査の出典</a></section></main>',text:'当社調査の対象は利用者です。調査期間2026年。'});
assert.equal(rich.signals.definition,true);
assert.equal(rich.signals.semantic,true);
assert.equal(rich.signals.canonical,true);
assert.equal(rich.signals.sourceLink,true);
assert.deepEqual(rich.details.primaryKinds,['survey']);
assert.equal(rich.details.pageKind,'service');
assert.equal(inspectDocument({url,html:'<h1>概要</h1><h3>詳細</h3>',text:'とは とは とは'}).signals.definition,false);
assert.equal(inspectDocument({url,html:'<h1>概要</h1><h3>詳細</h3>'}).signals.hierarchy,false);
assert.equal(inspectDocument({url,html:'<link rel="canonical" href="javascript:alert(1)">'}).signals.canonical,false);
assert.equal(inspectDocument({url,html:'<link rel="canonical" href="/a"><link rel="canonical" href="/b">'}).signals.canonical,false);
assert.equal(inspectDocument({url,text:'当社のサービスです',source:'firecrawl'}).signals.semantic,null);
assert.equal(buildInternalAudit([{internalEvidence:rich}]).supplemental.length,7);
assert.equal(buildInternalAudit([{internalEvidence:rich}]).measurementPlan.state,'unmeasured');
assert.ok(buildInternalAudit([]).supplemental.every(x=>x.state==='unknown'));
const old={url,native:true,signals:{},jsonld:null,links:null};
assert.ok(buildInternalAudit([{internalEvidence:old}]).supplemental.every(x=>['unknown','not_applicable'].includes(x.state)));
const original={entity:{score:61,findings:['旧評価']},schema:{score:25,findings:['旧評価']},citation:{score:30,findings:['旧評価']}};
const adapted=applyAuditKnowledge(original,fallback);
assert.equal(adapted.categories.entity.score,61);
assert.equal(adapted.categories.schema.score,25);
assert.ok(adapted.categories.schema.findings.some(x=>x.includes('確認・検討')));
assert.ok(!adapted.categories.schema.findings.some(x=>x.includes('検出しました')));
assert.ok(adapted.categories.citation.findings.some(x=>x.includes('確認・検討')));
assert.equal(original.entity.findings[0],'旧評価');
assert.ok(adapted.actions.every(x=>!x.includes('機械可読')));
assert.ok(Object.values(adapted.categories).every(x=>x.findings.length<=3));
assert.deepEqual(Object.keys(adapted.categories),Object.keys(original));
const second=inspectDocument({url:url+'service/missing',html:'<h2>業務支援サービス</h2><p>対象企業の業務を支援しています。</p>',text:'対象企業の業務を支援しています。'});
const mixed=buildInternalAudit([{internalEvidence:rich},{internalEvidence:second}]);
assert.equal(mixed.items.find(x=>x.id==='html').state,'partial');
const detailed=applyAuditKnowledge({structure:{score:60},entity:{score:50}},mixed);
assert.ok(detailed.categories.structure.findings.some(x=>x.includes(second.url)));
assert.ok(detailed.categories.structure.findings.some(x=>x.includes('H1見出しが0個')));
const enriched=enrichPageResults([{url:second.url,score:60}],mixed);
assert.ok(enriched[0].issues.some(x=>x.includes('見出し')));
assert.equal(enriched[0].score,60);
assert.ok(mixed.planning.questions.some(x=>x.includes('業務支援サービス')));
assert.equal(mixed.planning.measured,false);
