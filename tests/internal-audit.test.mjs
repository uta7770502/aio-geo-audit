assert.ok(precise.some(x=>x.key==='schema'&&x.state==='fix'&&x.evidence.includes('構文エラー')));
const narrow=applyAuditKnowledge({schema:{score:25}},buildInternalAudit([{internalEvidence:bad}]));
assert.ok(narrow.actions[0].includes('確認方法'));
