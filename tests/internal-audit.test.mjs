const sensible=buildSpecificRecommendations([brand,company]);
assert.ok(sensible.some(x=>x.key==='entity'&&x.state==='observed'&&x.evidence.includes('フランス菓子ブランド')));
assert.ok(sensible.some(x=>x.key==='trust'&&x.state==='observed'));
assert.ok(!sensible.some(x=>x.key==='schema'&&x.state==='fix'));
assert.ok(!sensible.some(x=>x.key==='structure'&&x.state==='fix'));
const validPage=inspectDocument({url:'https://brand.example/',html:'<h1>主題</h1><div itemscope itemtype="https://schema.org/Organization">ブランド</div>',text:'ブランド'});
assert.ok(buildSpecificRecommendations([validPage]).some(x=>x.key==='schema'&&x.state==='observed'));
